def HoldOut(df, hold_out_percent=0.20, evenly_picked=True, e_p_col='Plastic', rs=42, printFlag=True,
            chipGroup=None):
    """
    Split the df into a set for feature selection and a set for testing

    Parameters:
    -----------
    df : pandas.DataFrame
        The input dataframe to split
    hold_out_percent : float, default=0.20
        Percentage of data to hold out for testing (0.0 to 1.0)
    evenly_picked : bool, default=True
        If True, sample evenly from each category in e_p_col
        If False, sample randomly from entire dataframe
    e_p_col : str, default='Plastic'
        Column name to use for even sampling across categories
    rs : int, default=42
        Random state for reproducible results
    printFlag : bool, default=True
        If True, print summary statistics of the split
    chipGroup : int or None, default=None
        If provided (1-4), splits by 'Channel' column instead of random/even sampling:
            Group 1 → channels 0-3  become test_df
            Group 2 → channels 4-7  become test_df
            Group 3 → channels 8-11 become test_df
            Group 4 → channels 12-15 become test_df

    Returns:
    --------
    tuple : (fs_df, test_df)
        fs_df : DataFrame for feature selection (training)
        test_df : DataFrame for testing (held out)
    """

    # --- chipGroup branch: split by Channel column ---
    if chipGroup is not None:
        channel_ranges = {
            0: range(0, 4),
            1: range(4, 8),
            2: range(8, 12),
            3: range(12, 16),
        }

        if chipGroup not in channel_ranges:
            raise ValueError(f"chipGroup must be 0, 1, 2, or 3 (got {chipGroup})")

        test_channels = list(channel_ranges[chipGroup])
        test_df = df[df['Channel'].isin(test_channels)].copy()
        fs_df   = df[~df['Channel'].isin(test_channels)].copy()

        if printFlag:
            print(f"chipGroup={chipGroup} → test channels: {test_channels}")
            print(f"Original dataset size:      {len(df)}")
            print(f"Feature selection set size: {len(fs_df)}")
            print(f"Test set size:              {len(test_df)}")
            print(f"Actual hold-out percentage: {len(test_df)/len(df):.2%}")

            print("\nChannel distribution in test set:")
            print(test_df['Channel'].value_counts().sort_index())

            if e_p_col in df.columns:
                print(f"\n{e_p_col} distribution in test set:")
                print(test_df[e_p_col].value_counts())

        return fs_df, test_df

    # --- original branch: random or evenly-picked sampling ---
    np.random.seed(rs)

    unique_vals = df[e_p_col].unique()
    print(f"Unique values in {e_p_col}: {unique_vals}")

    if evenly_picked:
        test_indices = []

        for val in unique_vals:
            category_indices = df[df[e_p_col] == val].index.tolist()
            n_to_sample = max(1, int(len(category_indices) * hold_out_percent))

            if len(category_indices) >= n_to_sample:
                sampled_indices = np.random.choice(
                    category_indices,
                    size=n_to_sample,
                    replace=False
                ).tolist()
            else:
                sampled_indices = category_indices

            test_indices.extend(sampled_indices)

    else:
        n_test = int(len(df) * hold_out_percent)
        test_indices = np.random.choice(
            df.index,
            size=n_test,
            replace=False
        ).tolist()

    test_df = df.loc[test_indices].copy()
    fs_df   = df.drop(test_indices).copy()

    if printFlag:
        print(f"Original dataset size: {len(df)}")
        print(f"Feature selection set size: {len(fs_df)}")
        print(f"Test set size: {len(test_df)}")
        print(f"Actual hold-out percentage: {len(test_df)/len(df):.2%}")

        if evenly_picked:
            print("\nDistribution in test set:")
            print(test_df[e_p_col].value_counts())
            print(f"\nPercentage from each category:")
            for val in unique_vals:
                category_total = len(df[df[e_p_col] == val])
                category_test  = len(test_df[test_df[e_p_col] == val])
                if category_total > 0:
                    pct = category_test / category_total
                    print(f"{val}: {category_test}/{category_total} ({pct:.2%})")

    return fs_df, test_df
