def PrepXY(group_name, df, testSize=0.2, randomState=42, encodeYFlag=True, standardizeFlag=True,
           printFlag=False, valFlag=False, valSize=0.4, dataType="Slope", df_test=None,
           chipSplit=False, testChipGroup=0):
    """
    channelSplit: if True, split by channel groups instead of random split
    testChannelGroup: which channel group to use as test set (0=ch0-3, 1=ch4-7, 2=ch8-11, 3=ch12-15)
    """
    data = df.dropna(subset=[group_name])

    if dataType == 'Slope':
        X = data[data.columns[2:-7]]
    elif dataType == 'k':
        X = data[data.columns[2:-6]]
    elif dataType == 'bic':
        cols = [col for col in df.columns if col not in [group_name]]
        X = data[cols]

    y = data[group_name]

    if printFlag:
        display(X)

    if encodeYFlag:
        le = LabelEncoder()
        y_orig = y
        y = le.fit_transform(y)

    # ── Channel-based split ──────────────────────────────────────────────────
    if chipSplit:
        channel_groups = [(0, 3), (4, 7), (8, 11), (12, 15)]
        lo, hi = channel_groups[testChipGroup]
        test_mask  = data['Channel'].between(lo, hi)
        train_mask = ~test_mask

        X_train = X[train_mask]
        X_test  = X[test_mask]
        y_train = y[train_mask] if not encodeYFlag else y[train_mask]
        y_test  = y[test_mask]  if not encodeYFlag else y[test_mask]

    # ── Explicit test dataframe provided ────────────────────────────────────
    elif df_test is not None and dataType == 'k':
        X_test  = df_test[df_test.columns[2:-6]]
        y_test  = le.fit_transform(df_test[group_name])
        X_train = data[df_test.columns[2:-6]]
        y_train = le.fit_transform(data[group_name])

    # ── Default random split ─────────────────────────────────────────────────
    else:
        X_train, X_test, y_train, y_test = train_test_split(
            X, y, test_size=testSize, random_state=randomState
        )

    # ── Optional validation split ────────────────────────────────────────────
    if valFlag:
        X_train, X_val, y_train, y_val = train_test_split(
            X_train, y_train, test_size=valSize, random_state=randomState
        )
        if standardizeFlag:
            scaler = StandardScaler()
            X_train_scaled = scaler.fit_transform(X_train)
            X_test_scaled  = scaler.transform(X_test)
            X_val_scaled   = scaler.transform(X_val)
        return X_train, X_test, y_train, y_test, X_train_scaled, X_test_scaled, X, y, y_orig, le, X_val_scaled, X_val, y_val
    else:
        if standardizeFlag:
            scaler = StandardScaler()
            X_train_scaled = scaler.fit_transform(X_train)
            X_test_scaled  = scaler.transform(X_test)
        return X_train, X_test, y_train, y_test, X_train_scaled, X_test_scaled, X, y, y_orig, le
