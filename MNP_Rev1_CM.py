def RunXGBoost(group_name, df, printFlag=False, featureAnalysisFlag=False, residualsFlag=False, classificationReportFlag=False, randomState=42, cmFlag=False, FinalFlag=False, accuraciesFlag=False, f1Flag=False, swapLabel=False, dataType='Slope', BICFlag=False, kernelType=None, df_test=None):
    results = {}
    X_train, X_test, y_train, y_test, X_train_scaled, X_test_scaled, X, y, y_orig, le = PrepXY(group_name, df, printFlag=printFlag, randomState=randomState, dataType=dataType, df_test=df_test)
    if group_name == 'Group_PN' and df_test is not None:
        y_train = y_train.apply(lambda x: 0 if x=='Null' else 1)
        y_test = y_test.apply(lambda x: 0 if x=='Null' else 1)
    dtrain = xgb.DMatrix(X_train, label=y_train)
    dtest = xgb.DMatrix(X_test, label=y_test)
    params = {
        'objective': 'multi:softmax',  # Multi-class classification
        'num_class': len(np.unique(y)),  # Number of classes
        'eval_metric': ['merror', 'mlogloss'],  # Evaluation metric, merror for misclassification error
    }
    watchlist = [(dtrain, 'train'), (dtest, 'eval')]
    num_boost_round = 100
    evals_result = {}
    #model = xgb.train(params, dtrain, num_boost_round=num_boost_round, evals=watchlist, early_stopping_rounds=10, evals_result=evals_result, verbose_eval=False)
    model = xgb.train(params, dtrain, num_boost_round=num_boost_round, evals=watchlist, evals_result=evals_result, verbose_eval=False)

    # Get predictions from the trained model
    y_pred = model.predict(dtest)
    val_accuracy = accuracy_score(y_test, y_pred)

    eval_loss = evals_result["eval"]["mlogloss"]
    train_loss = evals_result["train"]["mlogloss"]
    eval_merror = evals_result["eval"]["merror"]
    train_merror = evals_result["train"]["merror"]
    train_accuracy = [1 - merror for merror in train_merror]
    eval_accuracy = [1 - merror for merror in eval_merror]


    if FinalFlag: #showing raw final results (maybe not best)
    # Print confusion matrix
        cm = confusion_matrix(y_test, y_pred)
        plt.figure(figsize=(8, 6))
        sns.heatmap(cm, annot=True, fmt="d", cmap="Blues", xticklabels=le.classes_, yticklabels=le.classes_)
        plt.xlabel('Predicted')
        plt.ylabel('Actual')
        plt.title(f'Final Model Confusion Matrix {str("-".join(y.unique()))}')
        plt.show()

        # Print the final tree (e.g., the 99th tree if num_boost_round=100)
        xgb.plot_tree(model, num_trees=num_boost_round - 1)
        plt.show()

    ############ BEST MODEL ############
    best_iteration = np.argmax(eval_accuracy)  # Find the index of the highest validation accuracy
    # Get the best model at that iteration
    evals_result = {}
    best_tree_dump = model.get_dump()[best_iteration]
    if printFlag:
        print(f"Final Validation Accuracy: {val_accuracy:.4f}")
        print(f"Final Training Loss: {train_loss[-1]}")
        print(f"Final Validation Loss: {eval_loss[-1]}")
        print(f"Final Training Misclassification Error: {train_merror[-1]}")
        print(f"Final Validation Misclassification Error: {eval_merror[-1]}")
        print(f"Final Training Accuracy: {train_accuracy[-1]}")
        print(f"Final Validation Accuracy: {eval_accuracy[-1]}")
        print(f"Best iteration (with highest validation accuracy): {best_iteration}")
        print(f"\033[1mBest Validation Accuracy: {eval_accuracy[best_iteration]:.4f}\033[0m")
    #model_best = xgb.train(params, dtrain, num_boost_round=best_iteration+1, evals=watchlist, early_stopping_rounds=10, evals_result=evals_result, verbose_eval=False)
    model_best = xgb.train(params, dtrain, num_boost_round=best_iteration+1, evals=watchlist, evals_result=evals_result, verbose_eval=False)
    y_pred_best = model_best.predict(dtest)
    val_accuracy_best = accuracy_score(y_test, y_pred_best)
    results['accuracy'] = val_accuracy_best
    if printFlag:
        print(val_accuracy_best)

    y_test_original = le.inverse_transform(y_test)
    #print(y_pred_best)
    y_pred_original = le.inverse_transform(y_pred_best.astype(int))
    #y_pred_original = le.inverse_transform(y_pred_encoded)

    # Calculate BIC if requested
    if BICFlag:
        # Get predictions with probabilities for log-likelihood calculation
        params_prob = params.copy()
        params_prob['objective'] = 'multi:softprob'
        model_prob = xgb.train(params_prob, dtrain, num_boost_round=best_iteration+1, verbose_eval=False)
        y_pred_proba = model_prob.predict(dtest)

        # Calculate log-likelihood
        n_samples = len(y_test)
        n_classes = len(np.unique(y))

        # Reshape probabilities if needed
        if len(y_pred_proba.shape) == 1:
            y_pred_proba = y_pred_proba.reshape(-1, n_classes)

        # Calculate log-likelihood
        log_likelihood = 0
        for i in range(n_samples):
            true_class = int(y_test[i])
            predicted_prob = y_pred_proba[i, true_class]
            # Add small epsilon to avoid log(0)
            predicted_prob = max(predicted_prob, 1e-15)
            log_likelihood += np.log(predicted_prob)

        # Calculate number of parameters
        # For XGBoost: roughly (num_trees * max_depth * num_features * num_classes)
        # This is an approximation as the actual parameter count depends on tree structure
        num_trees = best_iteration + 1
        max_depth = params.get('max_depth', 6)  # default XGBoost max_depth
        num_features = X_train.shape[1]
        # Approximate number of parameters (this is a rough estimate)
        k = num_trees * max_depth * num_features

        # Calculate BIC: BIC = -2 * log_likelihood + k * log(n)
        bic = -2 * log_likelihood + k * np.log(n_samples)

        results['bic'] = bic
        results['log_likelihood'] = log_likelihood
        results['num_parameters'] = k

        if printFlag:
            print(f"Log-likelihood: {log_likelihood:.4f}")
            print(f"Number of parameters (estimated): {k}")
            print(f"BIC: {bic:.4f}")

    if classificationReportFlag:
        print("Classification Report (XGBoost):\n", classification_report(y_test, y_pred))
    if f1Flag:
        if swapLabel:
            try:
                f1 = f1_score(y_test, y_pred,pos_label=0)
            except:
                f1 = f1_score(y_test, y_pred, pos_label='Plastic')
        else:
            f1 = f1_score(y_test, y_pred)
        results['f1_score'] = f1
    # Print confusion matrix
    if cmFlag:
        if f1Flag:
            print(f'F1 Score of the XGBoost model: {f1}')
        else:
            print(f'Accuracy of the XGBoost model: {val_accuracy_best}')
        cm = confusion_matrix(y_test, y_pred)
        plt.figure(figsize=(8, 6))
        sns.heatmap(cm, annot=True, fmt="d", cmap="Blues", xticklabels=le.classes_, yticklabels=le.classes_)
        plt.xlabel('Predicted')
        plt.ylabel('Actual')
        plt.title(f'XGBoost Model Confusion Matrix for {str("-".join(y_orig.unique()))}')
        plt.show()

    # Plot accuracies vs boosting round
    if accuraciesFlag:
        plt.figure(figsize=(12, 6))
        plt.subplot(1, 2, 1)
        plt.plot(range(len(train_accuracy)), train_accuracy, label='Training Accuracy')
        plt.plot(range(len(eval_accuracy)), eval_accuracy, label='Validation Accuracy')
        plt.xlabel('Boosting Round')
        plt.ylabel('Accuracy')
        plt.title('Training and Validation Accuracy over Boosting Rounds')
        plt.legend()
    if featureAnalysisFlag:
        feature_importance = model_best.get_score(importance_type='gain')
        feature_importance_df = pd.DataFrame(list(feature_importance.items()), columns=['Feature', 'Importance'])
        feature_importance_df = feature_importance_df.sort_values(by='Importance', ascending=False)
        top_n = int(len(feature_importance_df) * 0.201)
        top_features_df = feature_importance_df.head(top_n)
        top_features_df = top_features_df.reset_index(drop=True)
        if printFlag:
            print("Top 20% Important Features for XGBoost:\n", top_features_df)
        results['feature_importance'] = top_features_df
    return results
