def write_result(save_csv_path, row_dict):
    """Append a single result row to the CSV, writing header if file is new."""
    save_csv_path = Path(save_csv_path)
    file_exists = save_csv_path.exists()
    with save_csv_path.open("a", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(f, fieldnames=list(row_dict.keys()))
        if not file_exists:
            writer.writeheader()
        writer.writerow(row_dict)
