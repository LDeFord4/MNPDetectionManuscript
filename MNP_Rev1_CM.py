def load_existing_results(save_csv_path):
    """Load existing results as a set of (Model, Group_Name, Hold_Chip, Val_Chip) tuples."""
    existing = set()
    save_csv_path = Path(save_csv_path)
    if save_csv_path.exists():
        with save_csv_path.open("r", newline="", encoding="utf-8-sig") as f:
            content = f.read().strip()
            if not content:
                return existing
            f.seek(0)
            reader = csv.DictReader(f)
            for row in reader:
                existing.add((row["Model"], row["Group_Name"], row["Hold_Chip"], row["Val_Chip"], row["Kernel_Type"]))
    return existing
