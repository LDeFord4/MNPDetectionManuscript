        # Calculate number of parameters for LDA
        # For LDA: n_features * (n_classes - 1) for discriminant coefficients
        # + n_classes for class priors + n_features for means per class
        # + covariance matrix parameters (n_features * (n_features + 1) / 2)
        n_features = X_train_scaled.shape[1]
