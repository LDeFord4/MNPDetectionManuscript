def GridSearchFeatureSelection(group_name, df, model_func, min_features, max_features,
                                val_chip, scoring='accuracy', randomState=42, dataType='k',
                                printFlag=False, plotFlag=False, save_results=False,
                                result_filename=None, test_flag=False, kernelType='rbf',
                                swapLabel=False, chipSplit=False, chipGroup=0,
                                **model_kwargs):
    """ MakeFeatureCombos"""
    #if there are ties, need to collect all features and average val metrics
    if group_name == 'Group_PN':
        metric = 'f1_score'
        f1Flag=True
    elif group_name == 'Group_Full':
        metric = 'accuracy'
        f1Flag=False
    elif group_name == 'Group_MHLN':
        metric = 'accuracy'
        f1Flag = False
    feature_combos = MakeFeatureCombos(group_name, df, min_features, max_features)
    all_columns = df.columns.tolist()
    group_list = [item for item in all_columns if item.startswith("Group")]
    total = len(feature_combos)
    print(f"Total number of features combos for this run is {total}")
    results_store = [None] * total
    for i, f in enumerate(feature_combos):
        selected_columns = list(dict.fromkeys(["Channel", "Plastic"] + list(f) + group_list))
        subset_df = df[selected_columns].copy()
        results = model_func(group_name = group_name, df = subset_df, randomState=randomState,
                dataType=dataType, printFlag=False, featureAnalysisFlag=True,
                BICFlag=False, f1Flag=f1Flag, cmFlag=False, kernelType=kernelType,
                swapLabel=False, df_test=None, chipSplit=False, chipGroup=val_chip)
        results_store[i] = (results[metric], f)
    # Sort by metric value (descending)
    results_store.sort(key=lambda x: x[0], reverse=True)

    # Find best metric value
    best_metric = results_store[0][0]

    # Collect all string lists with the best metric value
    best_strings = []
    for metric_val, string_list in results_store:
        if metric_val == best_metric:
            best_strings.extend(string_list)
        else:
            break  # sorted, so no need to continue
    seen = set()
    unique_best_strings = []
    for s in best_strings:
        if s not in seen:
            seen.add(s)
            unique_best_strings.append(s)
    return best_metric, unique_best_strings
