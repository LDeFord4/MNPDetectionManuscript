def MakeFeatureCombos(group_name, df, n_features_min, n_features_max):
    """ Outputs a list of feature combinations given min and max number of features. """
    all_columns = df.columns.tolist()
    feature_list_int = [item for item in all_columns if not item.startswith("Group")]
    feature_list = [item for item in feature_list_int if item not in set(['Plastic', 'Channel'])]
    feature_combos = []
    for size in list(range(n_features_min, n_features_max + 1)):
        feature_combos.extend(combinations(feature_list, size))
    return feature_combos
