def RunLRL1(group_name, df, printFlag=False, featureAnalysisFlag=False, residualsFlag=False, classificationReportFlag=False, randomState=42, cvFold=5, solver='saga', cmFlag=False, f1Flag = False, swapLabel=True, dataType='Slope', BICFlag=False, kernelType=None, df_test=None):
    results = {}
    X_train, X_test, y_train, y_test, X_train_scaled, X_test_scaled, X, y, y_orig, le, X_val_scaled, X_val, y_val = PrepXY(group_name, df, printFlag=printFlag, randomState=randomState, valFlag=True, dataType=dataType, df_test=df_test)
    warnings.filterwarnings("ignore", category=ConvergenceWarning)
    log_reg_cv = LogisticRegressionCV(cv=cvFold, penalty='l1', solver=solver, max_iter=1000, class_weight='balanced')  # CV to find alpha
    log_reg_cv.fit(X_val_scaled, y_val)
    #warnings.filterwarnings("default", category=ConvergenceWarning) #Reset to default behavior

    ##### LR L1 w/ best alpha from CV #####
    lasso_logistic_best_alpha = LogisticRegression(penalty='l1', solver='saga', C=log_reg_cv.C_[0], max_iter=1000, class_weight='balanced')
    lasso_logistic_best_alpha.fit(X_train_scaled, y_train)

    y_pred = lasso_logistic_best_alpha.predict(X_test_scaled)
    accuracy = accuracy_score(y_test, y_pred)
    results['accuracy'] = accuracy
    if classificationReportFlag:
        print("Classification Report (LR L1):\n", classification_report(y_test, y_pred))
    if printFlag:
        print(f"Accuracy of the LR L1 model: {accuracy}")

    # Calculate BIC if requested
    if BICFlag:
        # Get predicted probabilities for log-likelihood calculation
        y_pred_proba = lasso_logistic_best_alpha.predict_proba(X_test_scaled)

        # Calculate log-likelihood
        log_likelihood = 0
        for i, true_label in enumerate(y_test):
            log_likelihood += np.log(y_pred_proba[i, true_label])

        # Count non-zero coefficients (effective parameters)
        n_params = np.sum(lasso_logistic_best_alpha.coef_ != 0) + 1  # +1 for intercept
        n_samples = len(y_test)

        # Calculate BIC: -2 * log_likelihood + k * log(n)
        bic = -2 * log_likelihood + n_params * np.log(n_samples)
        results['bic'] = bic

        if printFlag:
            print(f"BIC of the LR L1 model: {bic}")
            print(f"Number of non-zero parameters: {n_params}")
    if f1Flag:
        if swapLabel:
            try:
                f1 = f1_score(y_test, y_pred,pos_label=0)
            except:
                f1 = f1_score(y_test, y_pred, pos_label='Plastic')
        else:
            f1 = f1_score(y_test, y_pred)
        results['f1_score'] = f1
    # Generate and plot the confusion matrix
    if cmFlag:
        if f1Flag:
            print(f'F1 Score of the LRL1 model: {f1}')
        else:
            print(f'Accuracy of the LRL1 model: {accuracy}')
        cm = confusion_matrix(y_test, y_pred)
        plt.figure(figsize=(8, 6))
        sns.heatmap(cm, annot=True, fmt="d", cmap="Blues", xticklabels=le.classes_, yticklabels=le.classes_)
        plt.xlabel('Predicted')
        plt.ylabel('Actual')
        plt.title(f'Logistic Regression (L1) Model Confusion Matrix for {str("-".join(y_orig.unique()))}')
        plt.show()

    if featureAnalysisFlag:
        model_coef = lasso_logistic_best_alpha.coef_[0]
        feature_names = X.columns
        feature_importance = pd.DataFrame({'Feature': feature_names, 'Importance': model_coef})
        feature_importance = feature_importance.sort_values(by='Importance', key=abs, ascending=False)

        # Get top 20% of features
        top_n = int(len(feature_importance) * 0.201)
        top_features_df = feature_importance.head(top_n)
        top_features_df = top_features_df.reset_index(drop=True)
        if printFlag:
            print(f"Top 20% Features for LRL1:\n", top_features_df)
        results['feature_importance'] = top_features_df
    return results
