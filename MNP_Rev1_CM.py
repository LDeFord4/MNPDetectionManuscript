        n_params = (n_features * (n_classes - 1) +  # discriminant coefficients
                   (n_classes - 1) +  # class priors (one less due to constraint)
                   n_features * n_classes +  # class means
                   n_features * (n_features + 1) // 2)  # shared covariance matrix

        n_samples = len(y_test)

