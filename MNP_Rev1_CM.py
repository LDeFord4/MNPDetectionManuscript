def RunLR(group_name, df, printFlag=False, featureAnalysisFlag=False, residualsFlag=False, classificationReportFlag=False, randomState=42, cmFlag=False, f1Flag = False, swapLabel=False, dataType='Slope', BICFlag=False, kernelType=None, df_test=None, save_plot_name=None, recallFlag=False, chipSplit=False, chipGroup=0):
    results = {}
    X_train, X_test, y_train, y_test, X_train_scaled, X_test_scaled, X, y, y_orig, le = PrepXY(group_name, df, printFlag=printFlag, randomState=randomState, dataType=dataType, df_test=df_test, chipSplit=chipSplit,testChipGroup=chipGroup)
    if printFlag:
        print(X_train.columns[:20])
        print(f'Unique Y train values {np.unique(y_train, return_counts=True)}')
        print(f'Unique Y test values {np.unique(y_test, return_counts=True)}')
    model = LogisticRegression(solver='lbfgs', max_iter= 2000)
    model.fit(X_train, y_train)
    y_pred = model.predict(X_test)

    if printFlag:
        print(f"Logistic Regression with {group_name}")
        print("Intercept:", model.intercept_)
        print("Classes:", le.classes_)
        print("Iterations:", model.n_iter_)
    if classificationReportFlag:
        print("Classification Report (LR):\n", classification_report(y_test, y_pred))
    accuracy = accuracy_score(y_test, y_pred)
    #print(f'accuracy is {accuracy}')
    results['accuracy'] = accuracy

    # Calculate BIC if requested
    if BICFlag:
        # Get predicted probabilities for log-likelihood calculation
        y_pred_proba = model.predict_proba(X_test)

        # Calculate log-likelihood
        log_likelihood = 0
        for i, true_label in enumerate(y_test):
            log_likelihood += np.log(y_pred_proba[i, true_label])

        # Calculate number of parameters for standard Logistic Regression
        # For binary classification: n_features + 1 (intercept)
        # For multiclass: n_features * n_classes + n_classes (intercepts)
        n_features = X_train.shape[1]
        n_classes = len(model.classes_)

        if n_classes == 2:
            # Binary classification: only one set of coefficients needed
            n_params = n_features + 1  # coefficients + intercept
        else:
            # Multiclass: coefficients and intercept for each class
            n_params = n_features * n_classes + n_classes

        n_samples = len(y_test)

        # Calculate BIC: -2 * log_likelihood + k * log(n)
        bic = -2 * log_likelihood + n_params * np.log(n_samples)
        results['bic'] = bic

        if printFlag:
            print(f"BIC of the LR model: {bic}")
            print(f"Number of parameters: {n_params}")
            if n_classes == 2:
                print(f"  - Coefficients: {n_features}")
                print(f"  - Intercept: 1")
            else:
                print(f"  - Coefficients: {n_features * n_classes}")
                print(f"  - Intercepts: {n_classes}")

    if f1Flag:
        if swapLabel:
            try:
                f1 = f1_score(y_test, y_pred,pos_label=0)
            except:
                f1 = f1_score(y_test, y_pred, pos_label='Plastic')
        else:
            f1 = f1_score(y_test, y_pred)
        results['f1_score'] = f1
    if cmFlag:
        if f1Flag:
            print(f'F1 Score of the Logistic Regression model: {f1}')
        else:
            print(f'Accuracy of the Logistic Regression model: {accuracy}')
        cm = confusion_matrix(y_test, y_pred)
        plt.figure(figsize=(8, 6))
        sns.heatmap(cm, annot=True, fmt="d", cmap="Blues", xticklabels=le.classes_, yticklabels=le.classes_, annot_kws={"size": 16})
        plt.xlabel('Predicted', fontsize=16)
        plt.ylabel('Actual', fontsize=16)
        plt.xticks(fontsize=14)
        plt.yticks(fontsize=14)
        plt.title(f'LR Model Confusion Matrix for {str("-".join(y_orig.unique()))}', fontsize=18)
        if save_plot_name is not None:
            if f1Flag:
                plt.title(f'{save_plot_name.split("_")[1]} Confustion Matrix\nLR, n = {len(X_train)+len(X_test)}, F1 Score = {(f1 * 100.0):.1f}%', fontsize=18)
            else:
                plt.title(f'{save_plot_name.split("_")[1]} Confustion Matrix\nLR, n = {len(X_train)+len(X_test)}, Accuracy = {(accuracy* 100.0):.1f}%', fontsize=18)
            plt.savefig(save_plot_name, format='png', bbox_inches='tight')
            print(f"Saved PNG to {save_plot_name}")

            # Download the file
            files.download(save_plot_name)
        plt.show()
        results["CM"] = cm
        results["cm_labels"] = le.classes_
    if featureAnalysisFlag:
        model_coef = model.coef_[0]
        feature_names = X.columns
        feature_importance = pd.DataFrame({'Feature': feature_names, 'Importance': model_coef})
        feature_importance = feature_importance.sort_values(by='Importance', key=abs, ascending=False)
        top_n = int(len(feature_importance) * 0.201)
        top_features_df = feature_importance.head(top_n)
        top_features_df = top_features_df.reset_index(drop=True)
        if printFlag:
            print(f"Top 20% Features for LR:\n", top_features_df)
        results['feature_importance'] = top_features_df
    if recallFlag:
        recall = recall_score(y_test, y_pred, average= 'weighted',pos_label=1)
        print(f'Recall: {recall}')
        results['recall'] = recall
    if residualsFlag:
        misclassified = (y_pred != y_test).astype(int)
        misclassified_indices = np.where(misclassified)[0]
        #print(misclassified)
        mc_df = X_test.iloc[misclassified_indices]
        #print(mc_df)
        original_indices = X_test.iloc[misclassified_indices].index
        #print(original_indices)
