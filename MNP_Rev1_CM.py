def CMBuilder(group_name, df_entire, model_list, save_csv_path, kernelType,
                                randomState=42, dataType='k',
                                printFlag=True, save_results=False,
                                result_filename=None, test_flag=False,
                                swapLabel=False, chipSplit=False, chipGroup=0, all_model_flag=False,
                                **model_kwargs):
    """ CMBuilder builds confusion matrices after optimal models have been found """
    if all_model_flag:
        model_list = ["SVM", "LR", "LDA"]
    CSV_COLUMNS = ["model", "group_name", "hold_out_chip", "val_chip", "best_val", "best_features", "val_test", "kernel_type", "CM", "CM_labels"]
    MODEL_FUNCTIONS = {
        'SVM': RunSVM,
        'LDA': RunLDA,
        'LR': RunLR,
    }
    if group_name == 'Group_PN':
        metric = 'f1_score'
        f1Flag = True
    elif group_name == 'Group_Full':
        metric = 'accuracy'
        f1Flag = False
    elif group_name == 'Group_MHLN':
        metric = 'accuracy'
        f1Flag = False
    existing_results = load_existing_results(save_csv_path)
    print(f"Loaded {len(existing_results)} existing results from CSV")
    for model in model_list:
        model_func = MODEL_FUNCTIONS[model]

        # Run both kernels for SVM when all_model_flag is set, otherwise just the passed kernelType
        if model == "SVM" and all_model_flag:
            kernel_types = ["linear", "rbf"]
        else:
            kernel_types = [kernelType]

        for kt in kernel_types:
            print(f"Running {group_name} for {model} {kt}")
            for hold_out_chip in [0, 1, 2, 3]:  # per hold out data split
                df, df_test = HoldOut(df_entire, chipGroup=hold_out_chip, printFlag=False)
                val_results_metric = []
                val_results_features = []
                for val_chip in [0, 1, 2, 3]:  # per validation data split
                    if val_chip == hold_out_chip:
                        continue
                    key = (str(model), str(group_name), str(hold_out_chip), str(val_chip), str(kt))
                    if key in existing_results:
                        print(f"Skipping {model} {group_name} hold_out={hold_out_chip} val={val_chip}, kernel={kt} (already done)")
                        continue
                    best_val, best_features = GridSearchFeatureSelection(group_name, df, model_func, 1, 17, val_chip=val_chip, kernelType=kt, printFlag=False)
                    val_results_metric.append(best_val)
                    val_results_features.append(best_features)
                    print(f"Best validation metric value for {model} {group_name} hold out ({hold_out_chip}) val ({val_chip}) : {best_val}")
                    print(f"Combined unique strings: {best_features}")
                    all_columns = df.columns.tolist()
                    groups_list = [item for item in all_columns if item.startswith("Group")]
                    total_col = list(["Channel", "Plastic"]) + best_features + groups_list
                    df_test_use = df_test[total_col].copy()
                    results = model_func(group_name=group_name, df=df, randomState=randomState,
                        dataType=dataType, printFlag=False, featureAnalysisFlag=False,
                        BICFlag=False, f1Flag=f1Flag, cmFlag=True, kernelType=kt,
                        swapLabel=False, df_test=df_test_use, chipSplit=None)
                    val_test = results[metric]
                    cm = results["CM"]
                    cm_labels = results["cm_labels"]
                    print(f"Labels are {cm_labels}")
                    row = {
                        "Model": model,
                        "Group_Name": group_name,
                        "Hold_Chip": hold_out_chip,
                        "Val_Chip": val_chip,
                        "Best_Val": best_val,
                        "Features": best_features,
                        "Test_Metric": val_test,
                        "Kernel_Type": kt,
                        "CM": cm,
                        "CM_labels": cm_labels
                    }
                    write_result(save_csv_path, row)
                    existing_results.add(key)
    return None
